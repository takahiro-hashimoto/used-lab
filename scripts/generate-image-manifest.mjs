// ============================================================
// public/images/<カテゴリ>/ に実在する機種画像の一覧を生成する。
//
// DB の image 列にファイル名が入っていても実体が無いことがある
// （画像を後から配置する運用のため。実際 Galaxy Z Flip7 は image が空、
//   デスクトップMacは配置途中）。そのまま next/image に渡すと 500 になる。
//
// 以前はページ側で existsSync(join(process.cwd(), 'public', ...)) を
// 呼んで実在確認していたが、これはビルド時しか成立しない。
// 再生成（ISR）はサーバー上で走るため、ファイルシステムを前提にすると
// 環境によっては全画像が「無い」と判定される。
// ビルド時に一覧を焼き込んで、実行時はただの Set 参照にする。
// ============================================================

import { readdirSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

/** 機種画像を置いているディレクトリ。lib/data/hero-images.ts のカテゴリと対応 */
const CATEGORIES = ['iphone', 'ipad', 'watch', 'macbook', 'mac', 'galaxy', 'pixel', 'airpods']

const entries = []
for (const cat of CATEGORIES) {
  const dir = join(ROOT, 'public', 'images', cat)
  if (!existsSync(dir)) continue
  for (const file of readdirSync(dir)) {
    if (file.startsWith('.')) continue
    entries.push(`${cat}/${file}`)
  }
}
entries.sort()

// lib/generated/ は gitignore 済み。新規クローンでは存在しないので必ず作る
mkdirSync(join(ROOT, 'lib/generated'), { recursive: true })

writeFileSync(
  join(ROOT, 'lib/generated/model-images.ts'),
  `// Auto-generated by scripts/generate-image-manifest.mjs — do not edit manually\n` +
    `// public/images/<category>/ に実在するファイルの一覧（ビルド時に確定）\n\n` +
    `const FILES: ReadonlySet<string> = new Set([\n` +
    entries.map((e) => `  '${e}',`).join('\n') +
    `\n])\n\n` +
    `/**\n` +
    ` * public/images/<category>/<image> が実在するか。\n` +
    ` *\n` +
    ` * 実行時にファイルシステムを触らないので、どのランタイムでも同じ結果になる。\n` +
    ` * 画像を追加したら次のビルドで自動的に true になる。\n` +
    ` */\n` +
    `export function hasModelImage(category: string, image: string | null | undefined): boolean {\n` +
    `  return !!image && FILES.has(\`\${category}/\${image}\`)\n` +
    `}\n`,
)

console.log(`[build:assets] model images: ${entries.length}件`)
