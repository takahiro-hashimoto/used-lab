// ============================================================
// app/critical.css を TS モジュールとして焼き込む。
//
// 以前は app/layout.tsx が readFileSync で読んでいたが、これはビルド時
// （Node.js がある環境）でしか成立しない。ルートレイアウトはモジュール
// 読み込み時に評価されるため、ファイルシステムを持たない実行環境では
// 全ページが 500 になる。実際 Cloudflare Workers では
// 「[unenv] fs.readFileSync is not implemented yet!」で全滅した。
//
// 圧縮もここで済ませる。実行時にコメント除去や空白畳みをやる理由はない。
// ============================================================

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

const raw = readFileSync(join(ROOT, 'app/critical.css'), 'utf8')
const minified = raw
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/\s+/g, ' ')
  .replace(/\s*([{};,])\s*/g, '$1')
  .replace(/:\s+/g, ':')
  .trim()

mkdirSync(join(ROOT, 'lib/generated'), { recursive: true })
writeFileSync(
  join(ROOT, 'lib/generated/critical-css.ts'),
  `// Auto-generated by scripts/generate-critical-css.mjs — do not edit manually\n` +
    `// app/critical.css を圧縮して埋め込んだもの。編集は app/critical.css 側で行う\n\n` +
    `export const CRITICAL_CSS = ${JSON.stringify(minified)}\n`,
)

console.log(`[build:assets] critical css: ${(minified.length / 1024).toFixed(1)}KB`)
